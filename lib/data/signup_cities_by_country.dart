  /// Cities for [country], or empty if unknown (free-text still allowed).
  static List<String> citiesFor(String? country) {
    final key = (country ?? '').trim();
    if (key.isEmpty) return const [];
    return List<String>.unmodifiable(_cities[key] ?? const <String>[]);
  }

  /// Case-insensitive filter; empty [query] returns full list (capped).
  static List<String> suggest({
    required String? country,
    required String query,
    int limit = 40,
  }) {
    final all = citiesFor(country);
    if (all.isEmpty) return const [];
    final q = query.trim().toLowerCase();
    final filtered = q.isEmpty
        ? all
        : all.where((c) => c.toLowerCase().contains(q)).toList();
    if (filtered.length <= limit) return filtered;
    return filtered.take(limit).toList();
  }

  static bool hasCuratedList(String? country) =>
      citiesFor(country).isNotEmpty;
}
